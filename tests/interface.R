if (dir.exists('DistFamilyFit/R')) {
  for (f in list.files('DistFamilyFit/R', full.names = TRUE)) source(f)
} else library(DistFamilyFit)
expect_error <- function(expr) stopifnot(inherits(tryCatch(force(expr), error = identity), 'error'))
set.seed(44)
x <- sinh(rnorm(120)); y <- exp(.5 * rnorm(120))
file <- tempfile(fileext = '.csv')
d <- data.frame(id = paste0('sample_', seq_along(x)), first = x, second = y)
write.table(d, file, sep = ';', dec = ',', row.names = FALSE, quote = FALSE)
p <- read_fit_data(file, sep = ';', dec = ',', columns = c('first', 'second'))
stopifnot(nrow(p$data) == 120L, identical(names(p$data), c('first', 'second')))
stopifnot(max(abs(p$data$first - x)) < 1e-10, identical(p$audit$ignored_columns, 'id'))
expect_error(read_fit_data(file, sep = ',', dec = ','))
expect_error(read_fit_data(file, sep = ';', dec = ',')) # id must be explicitly excluded
expect_error(prepare_fit_data(d, columns = c('first', 'first')))
expect_error(prepare_fit_data(d, columns = 'missing'))
expect_error(prepare_fit_data(d, columns = 0))
expect_error(prepare_fit_data(data.frame(first = rep(1, 30))))
expect_error(prepare_fit_data(data.frame(first = as.character(x))))
converted <- prepare_fit_data(data.frame(first = as.character(x)), convert_numeric = TRUE)
stopifnot('first' %in% converted$audit$converted_columns)
expect_error(prepare_fit_data(data.frame(first = c('bad', as.character(x))), convert_numeric = TRUE))
expect_error(prepare_fit_data(data.frame(first = Sys.Date() + 1:30)))
# A repeated preprocessing step must preserve original row identifiers.
d$first[c(3, 9)] <- NA
p <- prepare_fit_data(d, columns = c('first', 'second'), na_action = 'omit')
p2 <- prepare_fit_data(p)
stopifnot(identical(p2$audit$excluded_rows, c(3L, 9L)), p2$audit$n_input == 120L)
m <- suppressWarnings(fit_johnson_multivariate(p))
stopifnot(m$audit$n_input == 120L, m$audit$n_retained == 118L, identical(m$audit$excluded_rows, c(3L, 9L)))
stopifnot(all(is.finite(m$mahalanobis_squared)), is.finite(m$joint_diagnostic_distance))
# Default/family selection and per-column independent fits.
u <- fit_univariate(x)
stopifnot(all(startsWith(u$ranking$model, 'Johnson')))
usl <- fit_johnson_univariate(x, types = 'SL')
stopifnot(identical(usl$ranking$model, 'JohnsonSL'))
expect_error(fit_johnson_univariate(x, types = 'normal'))
expect_error(fit_univariate(x, families = 'Unknown'))
a <- fit_columns(p, families = c('Burr', 'GLD'))
stopifnot(length(a) == 2L, all(names(a) == c('first', 'second')))
all <- fit_univariate(y, families = 'all')
stopifnot(nrow(all$ranking) == 7L)
stopifnot(any(all$ranking$model == 'BurrXII' & all$ranking$status %in% c('OK', 'Warning')))
# Descriptive threshold controls a warning, not a probability or acceptance.
tight <- fit_univariate(x, ks_warning = .001)
stopifnot(all(tight$ranking$status[tight$ranking$status != 'Failed'] != 'OK'))
stopifnot(all(grepl('descriptive', tight$ranking$note[tight$ranking$status == 'Warning'])))
# Subsample likelihood must not be reported as full-data MLE AIC.
us <- fit_univariate(x, max_fit_n = 60)
stopifnot(all(is.na(us$ranking$AIC)))
# Selection is reproducible under observation reordering; fits sort internally.
u2 <- fit_univariate(rev(x))
stopifnot(identical(u$best, u2$best), max(abs(u$ranking$KS - u2$ranking$KS), na.rm = TRUE) < 1e-10)
stopifnot(all(is.finite(transform_johnson(u, x))))
# Caller never receives a plot from an estimation function.
stopifnot(grDevices::dev.cur() == 1L)
pdf(file = tempfile(fileext = '.pdf'))
plot_fit(u); plot_fit(u, 'density'); plot_fit(u, 'qq')
plot_comparison(all); plot_dependence(m); plot_dependence(m, 'covariance')
plot_transformed(m); plot_transformed(m, 'mahalanobis')
invisible(dev.off())
# CSV headers are mandatory and unique; malformed rows are rejected.
writeLines(c('a,a', '1,2'), file)
expect_error(read_fit_data(file, min_n = 5))
writeLines(c('a,b', '1,2,3'), file)
expect_error(read_fit_data(file, min_n = 5))
cat('Data contract, family selection, diagnostics and visualization checks passed.\n')
